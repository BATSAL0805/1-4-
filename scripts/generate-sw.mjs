// Generates public/firebase-messaging-sw.js from the same VITE_FIREBASE_* values
// used by src/firebase.ts, so the Firebase config never has to be hardcoded or
// committed. Runs before `vite build` (and can be run manually for local testing).
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));
const fileEnv = loadEnv("production", root, "VITE_FIREBASE_");
const env = { ...fileEnv, ...process.env };

const config = {
  apiKey: env.VITE_FIREBASE_API_KEY,
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.VITE_FIREBASE_APP_ID,
};

const missing = Object.entries(config)
  .filter(([, value]) => !value)
  .map(([key]) => key);

if (missing.length > 0) {
  console.warn(
    `[generate-sw] Skipping: missing env vars (${missing.join(", ")}). ` +
      "Push notifications won't work until .env (or CI secrets) are set.",
  );
  process.exit(0);
}

const sdkVersion = "12.19.0";
const content = `// Auto-generated by scripts/generate-sw.mjs — do not edit by hand.
importScripts("https://www.gstatic.com/firebasejs/${sdkVersion}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${sdkVersion}/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title ?? "1-4 알림장";
  self.registration.showNotification(title, {
    body: payload.notification?.body ?? "",
  });
});
`;

mkdirSync(fileURLToPath(new URL("../public", import.meta.url)), { recursive: true });
writeFileSync(fileURLToPath(new URL("../public/firebase-messaging-sw.js", import.meta.url)), content);
console.log("[generate-sw] public/firebase-messaging-sw.js generated");
